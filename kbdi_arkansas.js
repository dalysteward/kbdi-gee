var accumulate = function(image, list) {
  
  var maxt = image.select('tmax').multiply(1.8).add(32).round().rename('maxt');
  var pow1 = ee.Image(0.0486).multiply(maxt).rename('pow1');
  var pow2 = ee.Image(-0.0441).multiply(avgclimE).rename('pow2');
  
  var previous = ee.Image(ee.List(list).get(-1)).select('KBDI_Total').rename('previous');
  
  var base_ppt = image.select('ppt').multiply(0.03937).rename('base_ppt');
  var prev_base = ee.Image(ee.List(list).get(-1)).select('base_ppt').rename('prev_base');
  var day1ppt = base_ppt.where(prev_base.gte(0), base_ppt.subtract(0.2)).rename('day1ppt');
  var day1zero = day1ppt.where(day1ppt.lte(0),0).rename('day1zero');
  var prev_day1 = ee.Image(ee.List(list).get(-1)).select('final_ppt').rename('prev_day1');
  var orig_ppt = day1zero.where(prev_day1.gt(0),base_ppt).rename('orig_ppt');
  var final_ppt = orig_ppt.where(orig_ppt.lte(0),0).rename('final_ppt');
  var ppt_addBands = final_ppt.addBands(base_ppt);
  
  var netp100 = final_ppt.multiply(100).rename('netp100');
  var Q = previous.where(previous.subtract(netp100).lt(0),0).rename('Q');
  var Qimage = Q.where(previous.subtract(netp100).gte(0),previous.subtract(netp100).round()).rename('Qimage');
  
  var dQtop1 = ee.Image(800).subtract(Qimage).rename('top1');
  var dQtop2 = ee.Image(2.71828).pow(pow1).multiply(0.968).subtract(8.3).rename('top2');
  var dQbottom = ee.Image(2.71828).pow(pow2).multiply(10.88).add(1).rename('bottom');
  var dQ = dQtop1.multiply(dQtop2).divide(dQbottom)
    .multiply(0.001).float().rename('dQ');
  var dQround = dQ.round().rename('dQ Rounded');
  var dQzeroed = dQround.where(dQround.lt(0),0);
  
  var KBDItotal = Qimage.add(dQzeroed).rename('KBDI_Total');
  var KBDIaddbands = KBDItotal.addBands(base_ppt).addBands(final_ppt);
  return ee.List(list).add(KBDIaddbands);
};

var KBDIcoll = ee.ImageCollection(ee.List(climate.iterate(accumulate, first)));
